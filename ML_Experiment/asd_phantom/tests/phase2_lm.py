"""
Phase 2 - LM trajectory generation for the augmented detection test.

Per FN-PHANTOM-002 Section 8.2.

Generates K continuations from EACH of the base and Instruct models on the
same prompts, with bilateral scoring (each trajectory is scored under both
models). This gives:
  - 1500 inst-mode trajectories: generated by Instruct, scored under both
  - 1500 base-mode trajectories: generated by base, scored under both

The classifier task in phase2_analysis.py is to distinguish inst-generated
from base-generated continuations using one of three feature sets:
  Set A (rho-only): mean_rho, std_rho
  Set B (ASD-only): drift, timing_cv, mean_depth_excess, isolated_frac,
                    Q_tail_1..4, r_plus
  Set C (combined): A + B

Sequential 3-pass model loading (load Inst -> generate inst-trajs and score
under Inst; load base -> cross-score inst-trajs under base AND generate
base-trajs and score under base; load Inst -> cross-score base-trajs under
Inst). Three model loads ~15s overhead total.

Expected runtime per FN-PHANTOM-002 §8.2.6 on RTX 4090:
  - 3000 generations x 256 tokens at 60 tok/s = ~3.6 hours generation
  - 3000 cross-scoring forward passes = ~3.5 hours
  - Encoder + features: ~2 minutes
  - Classifier training and CV: <5 minutes in scikit-learn
  - Total: ~12 hours

On RTX 5080 the rate observed in Phase 1 was ~0.08 generations/sec, so:
  - Generation 3000 at 0.08/s = ~10.4 hours
  - Cross-scoring 3000 (forward only, faster) = ~2-3 hours
  - Total wall-clock: ~13-15 hours
"""

from __future__ import annotations
import sys
import os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import json
import numpy as np
import pandas as pd
from src.asd_encoder import encode_and_walk
from src.asd_features import all_features, get_iid_null
from src import llm_trajectory as lt
from tests.phase2_topics import PHASE_2_TOPICS

import time


# ---- Operational defaults ----
DEFAULT_K = 100             # seeds per (topic, paraphrase, generating_model)
DEFAULT_T_GEN = 256
DEFAULT_TEMPERATURE = 0.7
DEFAULT_BLOCK_SIZE = 16
DEFAULT_SIGNAL = "C"
DEFAULT_MAX_DEPTH = 6


def build_specs(K, T_gen, temperature):
    """Build dual-origin generation specs for Phase 2.
    K seeds × 2 models × 5 paraphrases × 3 topics = 6K specs.
    """
    specs = []
    for topic_id, topic_data in PHASE_2_TOPICS.items():
        for p_idx, paraphrase in enumerate(topic_data["paraphrases"]):
            for seed in range(K):
                # inst-mode generation
                specs.append({
                    "prompt": paraphrase,
                    "seed": seed,
                    "T": T_gen,
                    "temperature": temperature,
                    "generating_model": "inst",
                    "meta_extra": {
                        "topic": topic_id,
                        "paraphrase_idx": p_idx,
                        "case_study": topic_data["case_study"],
                    },
                })
                # base-mode generation (different seed offset to avoid
                # accidental token overlap, though seeds are model-specific)
                specs.append({
                    "prompt": paraphrase,
                    "seed": seed + 1_000_000,  # offset for clarity
                    "T": T_gen,
                    "temperature": temperature,
                    "generating_model": "base",
                    "meta_extra": {
                        "topic": topic_id,
                        "paraphrase_idx": p_idx,
                        "case_study": topic_data["case_study"],
                        "base_seed_logical": seed,  # so inst seed=k pairs with base seed=k logically
                    },
                })
    return specs


def encode_and_extract(traj, block_size, null, signal="C",
                       max_depth=DEFAULT_MAX_DEPTH):
    sig = traj.signal(signal)
    if len(sig) < block_size:
        return {}
    rng = np.random.default_rng(traj.meta.get("seed", 0) + 7_000_000)
    ep = encode_and_walk(sig, block_size=block_size,
                          max_depth_tracked=max_depth, rng=rng)
    feats = all_features(ep, null)
    feats["mean_rho"] = float(np.mean(traj.rho))
    feats["std_rho"] = float(np.std(traj.rho))
    feats["mean_surp_inst"] = float(np.mean(traj.surprisal_inst))
    feats["mean_surp_base"] = float(np.mean(traj.surprisal_base))
    feats["T_actual"] = int(len(sig))
    return feats


def _save_trajectories(trajectories, specs, path):
    payload = {}
    for i, traj in enumerate(trajectories):
        if traj is None:
            continue
        payload[f"surp_inst_{i}"] = traj.surprisal_inst
        payload[f"surp_base_{i}"] = traj.surprisal_base
        payload[f"rho_{i}"] = traj.rho
    meta_list = []
    for i, (spec, traj) in enumerate(zip(specs, trajectories)):
        if traj is None:
            meta_list.append(None)
        else:
            meta_list.append({
                "i": i,
                "prompt": traj.prompt,
                "generation": traj.generation,
                "generating_model": traj.generating_model,
                "meta": traj.meta,
            })
    np.savez_compressed(path, **payload)
    with open(path + ".meta.json", "w", encoding="utf-8") as f:
        json.dump(meta_list, f, indent=2, ensure_ascii=False, default=str)


def _load_trajectories(path):
    with open(path + ".meta.json", "r", encoding="utf-8") as f:
        meta_list = json.load(f)
    arr = np.load(path)
    trajectories = []
    for m in meta_list:
        if m is None:
            trajectories.append(None)
            continue
        i = m["i"]
        trajectories.append(lt.Trajectory(
            prompt=m["prompt"],
            generation=m["generation"],
            surprisal_inst=arr[f"surp_inst_{i}"],
            surprisal_base=arr[f"surp_base_{i}"],
            rho=arr[f"rho_{i}"],
            generating_model=m["generating_model"],
            meta=m["meta"],
        ))
    return trajectories


def run_phase2(backend, output_csv_path, trajectory_cache_path,
                K=DEFAULT_K,
                T_gen=DEFAULT_T_GEN,
                temperature=DEFAULT_TEMPERATURE,
                block_size=DEFAULT_BLOCK_SIZE,
                signal=DEFAULT_SIGNAL,
                max_depth=DEFAULT_MAX_DEPTH):
    """Phase 2 generation + feature extraction."""
    n_topics = len(PHASE_2_TOPICS)
    n_pairs = sum(len(d["paraphrases"]) for d in PHASE_2_TOPICS.values())
    n_total = n_pairs * K * 2  # x2 because both models generate

    print()
    print(f"Phase 2 setup:")
    print(f"  Backend: {type(backend).__name__}")
    print(f"  Topics: {n_topics} (case-study-validated shaped topics)")
    print(f"  Pairs (topic, paraphrase): {n_pairs}")
    print(f"  K = {K} seeds per pair per generating model (so 2K per pair total)")
    print(f"  T_gen = {T_gen}, temperature = {temperature}")
    print(f"  Operational block_size = {block_size}, signal = Choice {signal}")
    print(f"  Total trajectories to generate: {n_total} ({n_pairs * K} inst + {n_pairs * K} base)")
    print(f"  Cache path: {trajectory_cache_path}")
    print()

    trajectories = None
    if trajectory_cache_path and os.path.exists(trajectory_cache_path):
        print(f"Loading cached trajectories from {trajectory_cache_path}")
        trajectories = _load_trajectories(trajectory_cache_path)
        n_loaded = sum(1 for t in trajectories if t is not None)
        print(f"  loaded {n_loaded} trajectories from cache (skipping LM passes)")

    if trajectories is None:
        specs = build_specs(K, T_gen, temperature)
        if len(specs) != n_total:
            print(f"  WARNING: build_specs gave {len(specs)} specs but expected {n_total}")
        trajectories = backend.generate_batch(specs, verbose_every=25)
        if trajectory_cache_path:
            print(f"\n  Saving trajectories to {trajectory_cache_path} ...")
            _save_trajectories(trajectories, specs, trajectory_cache_path)
            print(f"  saved.")

    n_total_resp = len(trajectories)
    trajectories = [t for t in trajectories if t is not None]
    n_ok = len(trajectories)
    n_inst = sum(1 for t in trajectories if t.generating_model == "inst")
    n_base = sum(1 for t in trajectories if t.generating_model == "base")
    if n_ok < n_total_resp:
        print(f"  WARNING: {n_total_resp - n_ok} trajectories failed; proceeding with {n_ok}")
    print(f"  Trajectory mix: inst={n_inst}, base={n_base}")

    # Encode
    print(f"\n=== Encoding {n_ok} trajectories at block_size={block_size}, signal=Choice {signal} ===")
    null = get_iid_null(T_gen, block_size=block_size)
    print(f"  IID null (b={block_size}): cancel_rate = {null['cancel_rate']:.4f} +- {null['cancel_rate_std']:.4f}")

    rows = []
    for traj in trajectories:
        topic = traj.meta.get("topic", "?")
        p_idx = traj.meta.get("paraphrase_idx", -1)
        seed = traj.meta.get("seed", -1)
        case_study = traj.meta.get("case_study", "?")
        feats = encode_and_extract(traj, block_size=block_size, null=null,
                                     signal=signal, max_depth=max_depth)
        if not feats:
            continue
        feats["topic"] = topic
        feats["case_study"] = case_study
        feats["paraphrase_idx"] = p_idx
        feats["seed"] = seed
        feats["generating_model"] = traj.generating_model
        feats["block_size"] = block_size
        feats["signal"] = signal
        rows.append(feats)

    df = pd.DataFrame(rows)
    df.to_csv(output_csv_path, index=False)
    print(f"  wrote {len(df)} rows -> {output_csv_path}")
    return df


def main():
    print("=" * 76)
    print("Phase 2 - LM trajectories for augmented detection test")
    print("=" * 76)

    # ---- Backend selection ------------------------------------------
    # Sandbox / no GPU:
    # backend = lt.MockLMBackend()

    # Real Llama on user GPU box (RTX 5080 16GB) -- 3-pass sequential:
    backend = lt.TransformersBackend(
        inst_model_name="meta-llama/Llama-3.1-8B-Instruct",
        base_model_name="meta-llama/Llama-3.1-8B",
        device="cuda",
    )
    # ----------------------------------------------------------------

    out_dir = os.path.join(os.path.dirname(__file__), "..", "results")
    os.makedirs(out_dir, exist_ok=True)
    suffix = "mock" if isinstance(backend, lt.MockLMBackend) else "llama"
    K = 5 if isinstance(backend, lt.MockLMBackend) else DEFAULT_K
    output_csv = os.path.join(out_dir, f"phase2_features_{suffix}.csv")
    cache = os.path.join(out_dir, f"phase2_trajectories_{suffix}.npz")

    df = run_phase2(backend, output_csv, cache, K=K)

    print()
    print("=" * 76)
    print("Done.")
    print("=" * 76)
    print(f"  Trajectory cache: {cache}")
    print(f"  Feature CSV:      {output_csv}")
    print()
    print(f"  Next: python tests/phase2_analysis.py {output_csv}")


if __name__ == "__main__":
    main()
